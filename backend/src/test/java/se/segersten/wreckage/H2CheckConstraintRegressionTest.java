package se.segersten.wreckage;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.sql.DriverManager;
import java.sql.SQLException;
import java.util.UUID;

import org.junit.jupiter.api.Test;

class H2CheckConstraintRegressionTest {

    @Test
    void evaluatesStatusConstraintAfterCreatingConnectionCloses() throws SQLException {
        String url = "jdbc:h2:mem:status-check-" + UUID.randomUUID()
                + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1;DATABASE_TO_LOWER=TRUE";
        try {
            try (var connection = DriverManager.getConnection(url, "sa", "");
                 var statement = connection.createStatement()) {
                statement.execute("""
                        CREATE TABLE game (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            status VARCHAR(20) NOT NULL,
                            CONSTRAINT chk_game_status
                                CHECK (status IN ('WAITING_FOR_PLAYERS', 'RUNNING', 'FINISHED'))
                        )
                        """);
            }

            try (var connection = DriverManager.getConnection(url, "sa", "");
                 var insert = connection.prepareStatement("INSERT INTO game (status, id) VALUES (?, DEFAULT)")) {
                insert.setString(1, "WAITING_FOR_PLAYERS");
                assertThat(insert.executeUpdate()).isEqualTo(1);

                insert.setString(1, "INVALID");
                assertThatThrownBy(insert::executeUpdate)
                        .isInstanceOfSatisfying(SQLException.class,
                                exception -> assertThat(exception.getSQLState()).isEqualTo("23513"));

                try (var statement = connection.createStatement();
                     var rows = statement.executeQuery("SELECT status FROM game")) {
                    assertThat(rows.next()).isTrue();
                    assertThat(rows.getString(1)).isEqualTo("WAITING_FOR_PLAYERS");
                    assertThat(rows.next()).isFalse();
                }
            }
        } finally {
            try (var connection = DriverManager.getConnection(url, "sa", "");
                 var statement = connection.createStatement()) {
                statement.execute("SHUTDOWN");
            }
        }
    }
}
