CREATE TABLE game (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain_id UUID NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    board_width INTEGER,
    board_height INTEGER,
    status VARCHAR(20) NOT NULL DEFAULT 'RUNNING',
    max_players INTEGER NOT NULL DEFAULT 12,
    join_timeout_seconds INTEGER NOT NULL DEFAULT 300,
    program_size INTEGER NOT NULL DEFAULT 3,
    planning_timeout_seconds INTEGER NOT NULL DEFAULT 120,
    join_deadline TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    board_edge_walls VARCHAR(20000) NOT NULL DEFAULT '',
    board_pits VARCHAR(20000) NOT NULL DEFAULT '',
    board_checkpoints VARCHAR(20000) NOT NULL DEFAULT '',
    round_limit INTEGER NOT NULL DEFAULT 6,
    checkpoint_score INTEGER NOT NULL DEFAULT 2,
    crash_penalty INTEGER NOT NULL DEFAULT -1,
    push_crash_score INTEGER NOT NULL DEFAULT 1,
    board_spawn_points VARCHAR(20000) NOT NULL DEFAULT '',
    board_conveyors VARCHAR(20000) NOT NULL DEFAULT '',
    board_rotators VARCHAR(20000) NOT NULL DEFAULT '',
    board_control_points VARCHAR(20000) NOT NULL DEFAULT '',
    control_point_score INTEGER NOT NULL DEFAULT 1,
    host_token_hash VARCHAR(64) NOT NULL DEFAULT 'legacy',
    weapon_crash_score INTEGER NOT NULL DEFAULT 1,
    map_id VARCHAR(255) NOT NULL DEFAULT 'legacy',
    map_name VARCHAR(255) NOT NULL DEFAULT 'Legacy',
    configured_map_id VARCHAR(255),
    board_obstacles VARCHAR(20000) NOT NULL DEFAULT '',
    CONSTRAINT uq_game_domain_id UNIQUE (domain_id),
    CONSTRAINT chk_game_board_width_positive CHECK (board_width IS NULL OR board_width > 0),
    CONSTRAINT chk_game_board_height_positive CHECK (board_height IS NULL OR board_height > 0),
    CONSTRAINT chk_game_status CHECK (status IN ('WAITING_FOR_PLAYERS', 'RUNNING', 'FINISHED')),
    CONSTRAINT chk_game_max_players CHECK (max_players > 0),
    CONSTRAINT chk_game_join_timeout CHECK (join_timeout_seconds > 0),
    CONSTRAINT chk_game_program_size CHECK (program_size BETWEEN 1 AND 5),
    CONSTRAINT chk_game_planning_timeout CHECK (planning_timeout_seconds > 0),
    CONSTRAINT chk_game_round_limit CHECK (round_limit > 0)
);

CREATE TABLE player (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain_id UUID NOT NULL,
    game_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    access_token_hash VARCHAR(64) NOT NULL DEFAULT 'legacy',
    score INTEGER NOT NULL DEFAULT 0,
    visited_checkpoints VARCHAR(20000) NOT NULL DEFAULT '',
    crashes INTEGER NOT NULL DEFAULT 0,
    automated BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_player_domain_id UNIQUE (domain_id),
    CONSTRAINT uq_player_game_name UNIQUE (game_id, name),
    CONSTRAINT chk_player_crashes_nonnegative CHECK (crashes >= 0),
    CONSTRAINT fk_player_game FOREIGN KEY (game_id) REFERENCES game (id) ON DELETE CASCADE
);

CREATE TABLE vehicle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id BIGINT,
    position_x DOUBLE PRECISION NOT NULL,
    position_y DOUBLE PRECISION NOT NULL,
    direction VARCHAR(50) NOT NULL,
    domain_id UUID,
    player_domain_id UUID,
    game_id BIGINT,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    spawn_x INTEGER NOT NULL DEFAULT 0,
    spawn_y INTEGER NOT NULL DEFAULT 0,
    spawn_direction VARCHAR(50) NOT NULL DEFAULT 'SOUTH',
    damage INTEGER NOT NULL DEFAULT 0,
    rocket_ammo INTEGER NOT NULL DEFAULT 1,
    primary_weapon VARCHAR(32) NOT NULL DEFAULT 'LASER',
    special_ability VARCHAR(32) NOT NULL DEFAULT 'SHIELD',
    CONSTRAINT uq_vehicle_domain_id UNIQUE (domain_id),
    CONSTRAINT uq_vehicle_player_domain_id UNIQUE (player_domain_id),
    CONSTRAINT chk_vehicle_status CHECK (status IN ('ACTIVE', 'CRASHED')),
    CONSTRAINT chk_vehicle_damage_non_negative CHECK (damage >= 0),
    CONSTRAINT chk_vehicle_rocket_ammo CHECK (rocket_ammo BETWEEN 0 AND 1),
    CONSTRAINT chk_vehicle_primary_weapon CHECK (primary_weapon IN ('LASER', 'REPULSOR', 'ROCKET')),
    CONSTRAINT chk_vehicle_special_ability CHECK (special_ability IN ('TURBO', 'SHIELD', 'SIDE_STEP', 'ANCHOR')),
    CONSTRAINT fk_vehicle_player FOREIGN KEY (player_id) REFERENCES player (id) ON DELETE CASCADE,
    CONSTRAINT fk_vehicle_game FOREIGN KEY (game_id) REFERENCES game (id) ON DELETE CASCADE
);

CREATE TABLE vehicle_segment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL,
    segment_index INTEGER NOT NULL,
    type VARCHAR(50) NOT NULL,
    CONSTRAINT uq_vehicle_segment_index UNIQUE (vehicle_id, segment_index),
    CONSTRAINT fk_vehicle_segment_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicle (id) ON DELETE CASCADE
);

CREATE TABLE game_round (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id BIGINT NOT NULL,
    round_number INTEGER NOT NULL,
    phase VARCHAR(20) NOT NULL,
    program_payload VARCHAR(20000) NOT NULL,
    initial_state_payload VARCHAR(20000) NOT NULL,
    playback_payload VARCHAR(30000) NOT NULL,
    planning_deadline TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    initiative_payload VARCHAR(20000) NOT NULL DEFAULT '',
    initial_scores_payload VARCHAR(20000) NOT NULL DEFAULT '',
    start_events_payload VARCHAR(30000) NOT NULL DEFAULT '',
    CONSTRAINT uq_game_round_game UNIQUE (game_id),
    CONSTRAINT chk_round_phase CHECK (phase IN ('PLANNING', 'RESOLVING', 'PLAYBACK')),
    CONSTRAINT fk_game_round_game FOREIGN KEY (game_id) REFERENCES game (id) ON DELETE CASCADE
);

CREATE INDEX idx_player_game_id ON player (game_id);
CREATE INDEX idx_vehicle_player_id ON vehicle (player_id);
